"""Generates the app icon (src/Assets/app.ico), the MSIX/Store images (packaging/msix/Assets)
and the README images (docs/images).

The logo is the same mark as the tray icon: a dark disc with a blue "sentinel eye" ring.
Run:  python tools/make-assets.py   (needs Pillow)
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
DARK = (0x1C, 0x1D, 0x22, 255)
BLUE = (0x4C, 0x9A, 0xFF, 255)
RIM = (0xFF, 0xFF, 0xFF, 40)
STATES = [  # same colours as the app (MainWindow.xaml / TrayIcon.cs)
    ("Waiting for you", (0xFF, 0xA2, 0x3E, 255), 1),
    ("Working", (0x4C, 0x9A, 0xFF, 255), 2),
    ("Done", (0x3D, 0xD6, 0x8C, 255), 0),
    ("Idle", (0x8E, 0x90, 0x9A, 255), 0),
]
FONTS = Path("C:/Windows/Fonts")


def font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    name = "segoeuib.ttf" if bold else "segoeui.ttf"
    try:
        return ImageFont.truetype(str(FONTS / name), size)
    except OSError:
        return ImageFont.load_default()


def logo(size: int) -> Image.Image:
    """Draws the mark at 8x and downsamples, for smooth edges at every size."""
    big = size * 8
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    pad = big * 0.02
    d.ellipse([pad, pad, big - pad, big - pad], fill=DARK, outline=RIM, width=max(1, big // 64))
    ring = big * 0.22
    d.ellipse([ring, ring, big - ring, big - ring], outline=BLUE, width=int(big * 0.085))
    core = big * 0.405
    d.ellipse([core, core, big - core, big - core], fill=BLUE)
    return img.resize((size, size), Image.LANCZOS)


def tile(width: int, height: int, scale: float) -> Image.Image:
    """Transparent tile with the logo centred, `scale` = logo height / tile height."""
    img = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    side = int(height * scale)
    img.alpha_composite(logo(side), ((width - side) // 2, (height - side) // 2))
    return img


def main() -> None:
    src_assets = ROOT / "src" / "Assets"
    src_assets.mkdir(parents=True, exist_ok=True)
    sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256]
    logo(256).save(src_assets / "app.ico", sizes=[(s, s) for s in sizes])

    msix = ROOT / "packaging" / "msix" / "Assets"
    msix.mkdir(parents=True, exist_ok=True)
    tile(44, 44, 1.0).save(msix / "Square44x44Logo.png")
    tile(150, 150, 0.66).save(msix / "Square150x150Logo.png")
    tile(310, 150, 0.66).save(msix / "Wide310x150Logo.png")
    tile(50, 50, 1.0).save(msix / "StoreLogo.png")
    # Unplated taskbar/Start icons (used when resources.pri is generated by build.ps1)
    for s in (16, 24, 32, 48, 256):
        logo(s).save(msix / f"Square44x44Logo.targetsize-{s}_altform-unplated.png")
    # Store listing logo (300x300) for Partner Center
    store = ROOT / "packaging" / "store"
    store.mkdir(parents=True, exist_ok=True)
    tile(300, 300, 0.9).save(store / "StoreListingLogo-300.png")
    readme_images(ROOT / "docs" / "images")
    print("Assets written to", src_assets, msix, "and docs/images")


def tray_icon(color, count: int, size: int) -> Image.Image:
    """The tray icon as drawn by TrayIcon.cs: a coloured disc with the number of active tasks."""
    big = size * 8
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.ellipse([big * 0.03, big * 0.03, big * 0.97, big * 0.97], fill=color)
    if count:
        f = font(int(big * 0.62), bold=True)
        d.text((big / 2, big / 2 + big * 0.02), str(count), font=f, fill=DARK, anchor="mm")
    else:
        c = big * 0.34
        d.ellipse([c, c, big - c, big - c], fill=DARK)
    return img.resize((size, size), Image.LANCZOS)


def readme_images(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)

    # Banner: logo, name and tagline on the app's dark background
    w, h = 1280, 320
    banner = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(banner)
    d.rounded_rectangle([0, 0, w - 1, h - 1], radius=36, fill=(0x16, 0x17, 0x1B, 255))
    banner.alpha_composite(logo(176), (96, (h - 176) // 2))
    d.text((320, 92), "LePa Sentinel", font=font(84, bold=True), fill=(0xEC, 0xEC, 0xEF, 255))
    d.text((324, 196), "A tray monitor for Claude Code on Windows", font=font(38), fill=(0x8E, 0x90, 0x9A, 255))
    x = 324
    for _, color, _ in STATES:
        d.ellipse([x, 258, x + 18, 276], fill=color)
        x += 34
    banner.save(out / "banner.png")

    # Tray icon states with labels
    cell, pad = 240, 24
    strip = Image.new("RGBA", (cell * len(STATES), 190), (0, 0, 0, 0))
    d = ImageDraw.Draw(strip)
    d.rounded_rectangle([0, 0, strip.width - 1, strip.height - 1], radius=24, fill=(0x16, 0x17, 0x1B, 255))
    for i, (label, color, count) in enumerate(STATES):
        cx = i * cell + cell // 2
        strip.alpha_composite(tray_icon(color, count, 72), (cx - 36, pad + 10))
        d.text((cx, 140), label, font=font(30, bold=True), fill=(0xEC, 0xEC, 0xEF, 255), anchor="mm")
    strip.save(out / "tray-states.png")

    logo(128).save(out / "logo.png")


if __name__ == "__main__":
    main()
